const fs=require('node:fs');
const assert=require('node:assert/strict');
const {startFixture}=require('./functional-fixture.cjs');
const {once}=require('node:events');
const {chromium}=require('@playwright/test');
if(!process.argv[2])throw Error('Indica el state.json generado por functional-fixture.cjs.');
const state=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
if(!/^http:\/\/localhost\/thesisguard_functional_[a-f0-9]{8}\/$/.test(state.url))throw Error('Solo se permiten instalaciones locales aisladas.');
const artifacts='tests/artifacts/functionality';fs.mkdirSync(artifacts,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});let lock;const errors=[];let passed=0;
 const check=(ok,label)=>{assert.ok(ok,label);passed++;console.log('OK '+label);};
 const contexts={};
 const call=async(role,action,method='GET',data={},id=null)=>{
  const request=contexts[role].request,session=await(await request.get(state.url+'api.php?action=session')).json();
  const r=await request.fetch(state.url+'api.php?'+new URLSearchParams({action,...(id===null?{}:{id})}),{method,headers:{'Content-Type':'application/json','X-CSRF-Token':session.csrf},...(method==='GET'?{}:{data})});
  return {status:r.status(),data:await r.json()};
 };
 try{
  for(const role of ['admin','coordinator','reviewer','student']){
   contexts[role]=await browser.newContext();
   check((await call(role,'login','POST',{email:role+'@test.local',password:state.password})).status===200,'Acceso '+role);
  }
  const project=state.projects[0];
  for(const [value,label] of [['   ','espacios'],[['invalido'],'listas'],[{},'objetos']])check((await call('student','project','PATCH',{title:value},project)).status===422,'Título rechaza '+label);
  check((await call('student','project','PATCH',{visibility:'incorrecta'},project)).status===422,'Visibilidad inválida devuelve validación');
  check((await call('admin','users','POST',{name:'Prueba',email:'new@test.local',password:'UnaClaveLarga123',role:'root',career_id:1})).status===422,'Rol inválido devuelve validación');
  check((await call('admin','users','PATCH',{active:'false'},state.users.student)).status===422,'No interpreta texto como activación');
  check((await call('admin','users','PATCH',{},state.users.student)).status===422,'No desactiva una cuenta por un campo omitido');
  for(const raw of ['{invalido','[]','null'])check((await call('student','project','PATCH',raw,project)).status===400,'JSON inválido rechazado: '+raw);
  check((await call('student','project','PATCH',{keywords:'control de prueba'},project)).status===200,'Actualización parcial válida');
  const p=(await call('student','project','GET',{},project)).data.project;
  check(p.title==='Privado estudiante'&&p.keywords==='control de prueba','Editar un campo conserva los demás');
  check((await call('student','analyze','POST',{consent:true},project)).status===409,'No analiza silenciosamente una versión anterior');
  check((await call('student','process-job','POST',{},999999)).status===404,'Tarea inexistente devuelve 404');
  check((await call('student','retry','POST',{},state.jobs[0])).status===409,'No reintenta una tarea completada');
  check((await call('student','process-job','POST',{},state.jobs[1])).status===409,'Tarea fallida exige reintento explícito');
  await call('coordinator','assignments','POST',{reviewer_id:state.users.reviewer},project);
  check((await call('reviewer','jobs')).data.items.every(j=>!j.can_process),'Docente asignado ve tareas sin permisos de modificación');
  check((await call('reviewer','retry','POST',{},state.jobs[1])).status===403,'Servidor impide reintento de solo lectura');
  check((await call('reviewer','process-job','POST',{},state.jobs[2])).status===403,'Servidor impide procesamiento de solo lectura');
  lock=startFixture('lock',state.fixture);
  const locked=await once(lock.stdout,'data');check(String(locked[0]).includes('LOCKED'),'Bloqueo de procesamiento para probar concurrencia');
  const busy=await call('student','process-job','POST',{},state.jobs[2]);
  check(busy.status===200&&busy.data.status==='pendiente','Procesador ocupado conserva la tarea pendiente');
  const released=once(lock,'exit');lock.stdin.end('\n');await released;lock=null;
  const page=await contexts.student.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(state.url+'#/jobs');
  await page.locator('[data-job="'+state.jobs[1]+'"]').click();
  await page.waitForFunction(id=>!document.querySelector('[data-job="'+id+'"]'),state.jobs[1]);
  const retried=(await call('student','jobs')).data.items.find(j=>Number(j.id)===state.jobs[1]);
  check(retried.status==='completado'&&Number(retried.attempts)===1,'Reintentar desde interfaz procesa el PDF');
  const resumed=await call('student','process-job','POST',{},state.jobs[2]);
  check(resumed.data.status==='completado','Continúa una tarea pendiente');
  await page.reload();await page.locator('[data-job="'+state.jobs[3]+'"]').click();
  await page.waitForFunction(id=>!document.querySelector('[data-job="'+id+'"]'),state.jobs[3]);
  check((await call('student','document','GET',{},state.docs[3])).data.status==='completado','Recupera una tarea interrumpida');
  check(!(await page.content()).includes('start-worker.ps1'),'Pantalla sin instrucciones del worker inexistente');
  await page.screenshot({path:artifacts+'/tasks.png',fullPage:true});
  const reviewerPage=await contexts.reviewer.newPage();await reviewerPage.goto(state.url+'#/jobs');
  await reviewerPage.getByRole('heading',{name:'Cada tarea tiene su seguimiento.'}).waitFor();
  check(await reviewerPage.locator('[data-job]').count()===0,'Interfaz oculta procesamiento a lectores');
  const session=await(await contexts.student.request.get(state.url+'api.php?action=session')).json();
  const noCsrf=await contexts.student.request.post(state.url+'api.php?action=process-job&id='+state.jobs[2],{data:{}});
  check(noCsrf.status()===403,'Procesamiento exige token del formulario');
  const upload=async(name,buffer)=>contexts.student.request.post(state.url+'api.php?action=upload&id='+project,{headers:{'X-CSRF-Token':session.csrf},multipart:{file:{name,mimeType:'application/octet-stream',buffer}}});
  check((await upload('archivo.exe',Buffer.from('invalido'))).status()===422,'Carga rechaza extensiones no admitidas');
  check((await upload('archivo.pdf',Buffer.from('invalido'))).status()===422,'Carga rechaza PDF con contenido inválido');
  const pdf=fs.readFileSync(state.fixture+'/storage/documents/'+fs.readdirSync(state.fixture+'/storage/documents')[0]);
  const uploaded=await upload('nuevo.pdf',pdf),uploadedData=await uploaded.json();
  check(uploaded.status()===201&&uploadedData.status==='completado'&&uploadedData.characters>80,'Carga PDF real y extrae texto');
  const details=(await call('student','document','GET',{},uploadedData.id)).data;
  check(!('path' in details)&&!('extracted_text' in details)&&details.excerpt.length>80,'Consulta documental devuelve vista previa sin ruta privada');
  const download=await contexts.student.request.get(state.url+'api.php?action=download&id='+uploadedData.id);
  check(download.status()===200&&(await download.body()).equals(pdf),'Descarga conserva el PDF original');
  check((await call('student','analyze','POST',{consent:false},project)).status===422,'Análisis exige consentimiento');
  const analysis=await call('student','analyze','POST',{consent:true},project);
  check(analysis.status===201&&analysis.data.status==='error','Falta de clave Gemini queda como error visible sin llamadas externas');
  const job=(await call('student','jobs')).data.items.find(j=>j.kind==='analysis'&&Number(j.target_id)===analysis.data.id);
  const retry=await call('student','retry','POST',{},job.id);
  check(retry.data.status==='error'&&retry.data.error,'Reintento de análisis devuelve el resultado real');
  const report=await call('student','reports','POST',{},state.analysis);
  check(report.status===201&&report.data.id,'Emite informe del análisis de prueba');
  const reportPdf=await contexts.student.request.get(state.url+'api.php?action=download&type=report&id='+report.data.id);
  check(reportPdf.status()===200&&(await reportPdf.body()).subarray(0,5).toString()==='%PDF-','Descarga informe PDF válido');
  check(errors.length===0,'Sin errores JavaScript en tareas');
  fs.writeFileSync(artifacts+'/result.json',JSON.stringify({passed,errors,externalAIRequests:0},null,2));
  console.log(passed+' comprobaciones aprobadas.');
 }finally{if(lock)lock.stdin.end('\n');await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
